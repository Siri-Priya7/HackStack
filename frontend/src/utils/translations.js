/**
 * Clean Translation getter with strict language integrity
 * Returns target language string; falls back to English only if key doesn't exist.
 */
export function getTranslation(langCode, key) {
  const lang = TRANSLATIONS[langCode] || TRANSLATIONS['en-IN'];
  if (lang && lang[key]) return lang[key];
  if (TRANSLATIONS['en-IN'][key]) return TRANSLATIONS['en-IN'][key];
  if (TRANSLATIONS['hi-IN'][key]) return TRANSLATIONS['hi-IN'][key];
  return key;
}

